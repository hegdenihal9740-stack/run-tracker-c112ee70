export function LoginScreen() {
  const [mode, setMode] = useState<"in" | "up">("in");
  const [email, setEmail] = useState("");
  const [password, setPassword] = useState("");
  const [busy, setBusy] = useState(false);

  async function submit(e: FormEvent) {
    e.preventDefault();
    setBusy(true);
    const { data, error } =
      mode === "in"
        ? await supabase.auth.signInWithPassword({ email, password })
        : await supabase.auth.signUp({
            email,
            password,
            options: { emailRedirectTo: window.location.origin },
          });
    setBusy(false);
    if (error) return void toast.error(error.message);
    if (mode === "up" && !data.session) toast.success("Check your email to confirm your account.");
  }

  async function forgot() {
    if (!email) return void toast.error("Enter your email first");
    const { error } = await supabase.auth.resetPasswordForEmail(email, {
      redirectTo: `${window.location.origin}/reset-password`,
    });
    if (error) toast.error(error.message);
    else toast.success("Password reset link sent.");
  }

  async function google() {
    const r = await lovable.auth.signInWithOAuth("google", { redirect_uri: window.location.origin });
    if (r.error) toast.error(String(r.error.message ?? r.error));
  }

  return (
    <div className="hr-login">
      <form className="hr-login-card" onSubmit={submit}>
        <span className="hr-brand-mark"><Layers size={22} /></span>
        <h1>{mode === "in" ? "Sign in to HR Management" : "Create your HR account"}</h1>
        <div className="hr-field">
          <label htmlFor="email">Email</label>
          <input id="email" type="email" required value={email} onChange={(e) => setEmail(e.target.value)} />
        </div>
        <div className="hr-field">
          <label htmlFor="password">Password</label>
          <input id="password" type="password" required minLength={6} value={password} onChange={(e) => setPassword(e.target.value)} />
        </div>
        <Button type="submit" disabled={busy}>{mode === "in" ? "Sign in" : "Sign up"}</Button>
        <Button type="button" variant="outline" className="hr-google" onClick={google}>
          <GoogleLogo /> Continue with Google
        </Button>
        <div className="hr-login-links">
          <button type="button" onClick={() => setMode(mode === "in" ? "up" : "in")}>
            {mode === "in" ? "No account? Sign up" : "Have an account? Sign in"}
          </button>
          {mode === "in" && <button type="button" onClick={forgot}>Forgot password?</button>}
        </div>
      </form>
    </div>
  );
}
